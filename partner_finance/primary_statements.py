"""Find statutory statement tables by title, period columns, scope and unit."""
from __future__ import annotations

import re
from datetime import date, timedelta

from .schema import FinancialFact, SourceDocument


TITLES = {
    "position": re.compile(r"\bconsolidated\s+(?:statements? of financial position|balance sheets?)\b", re.I),
    "profit": re.compile(r"\bconsolidated\s+(?:income statements?|statements? of (?:profit(?: or loss)?|operations))\b", re.I),
    "cash_flow": re.compile(r"\bconsolidated\s+statements? of cash flows?\b", re.I),
}
KOREAN_TITLES = {
    "position": "연결재무상태표",
    "profit": "연결포괄손익계산서",
    "cash_flow": "연결현금흐름표",
}
LABELS = {
    "position": [
        ("cash", r"Cash and cash equivalents"),
        ("accounts_receivable", r"Trade receivables"),
        ("current_assets", r"(?:Total )?current assets"),
        ("total_assets", r"Total assets"),
        ("total_equity", r"(?:Total )?equity"),
        ("retained_earnings", r"Retained earnings"),
        ("current_liabilities", r"(?:Total )?current liabilities"),
    ],
    "profit": [
        ("revenue", r"Revenue from contracts with customers|Revenue|Sales"),
        ("operating_income", r"Operating profit|Operating income"),
        ("net_income", r"Profit for the year|Year[’']s profit|Net (?:income|profit)"),
    ],
    "cash_flow": [
        ("operating_cash_flow", r"Cash flows? (?:generated by|from) operating activities|Net cash (?:generated by|from) operating activities"),
        ("investing_cash_flow", r"Cash flows? (?:used in|from) invest(?:ing|ment) activities|Net cash (?:used in|from) investing activities"),
        ("financing_cash_flow", r"Cash flows? (?:generated by \(used in\)|from) financing activities|Net cash (?:generated by|from) financing activities"),
    ],
}
ROW_PATTERNS = {section: [(item, re.compile(r"^(?:" + label + r")(?=\s|$)", re.I))
                          for item, label in aliases] for section, aliases in LABELS.items()}
KOREAN_LABELS = {
    "position": [("cash", "현금및현금성자산"), ("accounts_receivable", "매출채권"),
                 ("current_assets", "유동자산"), ("total_assets", "자산총계"),
                 ("total_equity", "자본총계"), ("retained_earnings", "이익잉여금"),
                 ("retained_earnings", "연결이익잉여금"),
                 ("current_liabilities", "유동부채")],
    "profit": [("revenue", "매출액"), ("operating_income", "영업이익"),
               ("net_income", "당기순이익")],
    "cash_flow": [("operating_cash_flow", "영업활동으로인한현금흐름"),
                  ("investing_cash_flow", "투자활동으로인한현금흐름"),
                  ("financing_cash_flow", "재무활동으로인한현금흐름")],
}
KOREAN_ROW_PATTERNS = {
    section: [(item, re.compile(r"^" + r"\s*".join(re.escape(char) for char in label) + r"(?=\s|\d|\()"))
              for item, label in aliases] for section, aliases in KOREAN_LABELS.items()
}
ROW_NUMBER = re.compile(r"^\s*(?:(?:[IVX]+|[ⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩ]+|\d+)\s*[.．]\s*)")
NUMBERS = re.compile(r"\(?-?\d[\d,]*(?:\.\d+)?\)?")
YEARS = re.compile(r"\b20\d{2}\b")
MONTHS = {name: number for number, name in enumerate(
    ("january", "february", "march", "april", "may", "june", "july", "august",
     "september", "october", "november", "december"), 1)}
CORE = {"revenue", "operating_income", "net_income", "total_assets", "total_equity",
        "current_assets", "current_liabilities", "operating_cash_flow"}
FLOW_ITEMS = {"revenue", "operating_income", "net_income", "operating_cash_flow",
              "investing_cash_flow", "financing_cash_flow"}


def _pages(text):
    matches = list(re.finditer(r"\[PAGE (\d+)\]", text))
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        yield int(match[1]), text[match.end():end]


def _statement_section(page, previous_cash_flow_page, page_no):
    first_lines = " ".join(line.strip() for line in page.splitlines()[:15])
    compact = re.sub(r"\s+", "", first_lines)
    for section, title in KOREAN_TITLES.items():
        if title in compact:
            return section
    if "연결손익계산서" in compact:
        return "profit"
    for section, title in TITLES.items():
        if title.search(first_lines):
            return section
    if previous_cash_flow_page == page_no - 1 and re.search(r"\binvest(?:ing|ment) activities\b", first_lines, re.I):
        return "cash_flow"
    return None


def _header_years(page):
    lines = page.splitlines()[:24]
    korean_years = list(dict.fromkeys(int(year) for year in re.findall(
        r"제\s*\d+\s*기\s*:\s*(20\d{2})\s*년", " ".join(lines))))
    if len(korean_years) == 2:
        return korean_years
    note_index = next((i for i, line in enumerate(lines) if re.search(r"\bNotes?\b", line, re.I)
                       and YEARS.search(line)), None)
    if note_index is not None:
        candidate = " ".join(lines[note_index:note_index + 5])
    else:
        candidate = next((line for line in lines if len(set(YEARS.findall(line))) == 2), "")
    ordered = list(dict.fromkeys(int(year) for year in YEARS.findall(candidate)))
    return ordered if len(ordered) == 2 else []


def _period_ends(page):
    header = " ".join(page.splitlines()[:14])
    found = {}
    for day, month, year in re.findall(r"\b(\d{1,2})[./-](\d{1,2})[./-](20\d{2})\b", header):
        try:
            found[int(year)] = date(int(year), int(month), int(day)).isoformat()
        except ValueError:
            pass
    for day, month, year in re.findall(r"\b(\d{1,2})\s+(January|February|March|April|May|June|July|August|September|October|November|December)\s+(20\d{2})\b", header, re.I):
        try:
            found[int(year)] = date(int(year), MONTHS[month.lower()], int(day)).isoformat()
        except ValueError:
            pass
    for year, month, day in re.findall(r"\b(20\d{2})\s*년\s*(\d{1,2})\s*월\s*(\d{1,2})\s*일", header):
        try:
            found[int(year)] = date(int(year), int(month), int(day)).isoformat()
        except ValueError:
            pass
    return found


def _annual_start(end):
    if not end:
        return ""
    closing = date.fromisoformat(end)
    try:
        previous_closing = closing.replace(year=closing.year - 1)
    except ValueError:
        previous_closing = date(closing.year - 1, 2, 28)
    return (previous_closing + timedelta(days=1)).isoformat()


def _currency_from_text(value):
    if re.search(r"€|\bEUR\b|\beuros?\b", value, re.I):
        return "EUR"
    if re.search(r"\bUSD\b|\bUS\s*dollars?\b|US\$", value, re.I):
        return "USD"
    if re.search(r"£|\bGBP\b|pounds? sterling", value, re.I):
        return "GBP"
    if re.search(r"\bKRW\b|\bKorean won\b|\bwon\b", value, re.I):
        return "KRW"
    return ""


def _unit_context(page, fallback_currency):
    header = " ".join(page.splitlines()[:18])
    korean_unit = re.search(r"\(\s*단\s*위\s*:\s*([^)]+)\)", header)
    if korean_unit:
        unit = re.sub(r"\s+", "", korean_unit.group(1))
        multiplier = {"원": 1, "천원": 1000, "백만원": 1_000_000}.get(unit)
        return ("KRW", multiplier) if multiplier else None
    unit = re.search(r"\(([^)]*(?:millions?|thousands?|[’'`]?000)[^)]*)\)", header, re.I)
    if not unit:
        return None
    phrase = unit.group(1)
    multiplier = 1_000_000 if re.search(r"millions?", phrase, re.I) else 1000
    currency = _currency_from_text(phrase) or fallback_currency
    return (currency, multiplier) if currency else None


def _fallback_currency(pages):
    for _, page in pages:
        lower = page.lower()
        if "functional and presentation currency" not in lower:
            continue
        match = re.search(r"functional and presentation currency.{0,1400}", page, re.I | re.S)
        if match:
            currency = _currency_from_text(match.group())
            if currency:
                return currency
    return ""


def _row_values(line, section, related_columns):
    line = " ".join(line.split())
    korean_line = ROW_NUMBER.sub("", line)
    patterns = [(item, pattern, line) for item, pattern in ROW_PATTERNS[section]]
    patterns += [(item, pattern, korean_line) for item, pattern in KOREAN_ROW_PATTERNS[section]]
    for item, pattern, candidate in patterns:
        match = pattern.match(candidate)
        if not match:
            continue
        tail = candidate[match.end():].strip()
        tokens = NUMBERS.findall(tail)
        if NUMBERS.sub("", tail).strip():
            continue
        if len(tokens) in (3, 5):
            tokens = tokens[1:]
        if len(tokens) == 4:
            if not related_columns:
                continue
            tokens = [tokens[0], tokens[2]]
        if len(tokens) != 2:
            continue
        values = []
        for token in tokens:
            negative = token.startswith("(") and token.endswith(")")
            value = float(token.strip("()").replace(",", ""))
            values.append(-value if negative else value)
        return item, candidate[:match.end()], values, line
    return None


def extract_primary_statements(text: str, entity_id: str, source: SourceDocument,
                               scope: str = "연결") -> tuple[list[FinancialFact], list[str]]:
    """Parse complete paired-year tables, never guessing position or currency."""
    if scope != "연결":
        return [], ["현재 규칙 기반 표 파싱은 연결 재무제표에만 적용합니다."]
    pages = list(_pages(text))
    if not pages:
        return [], ["PDF 페이지 표식을 찾지 못했습니다."]
    fallback_currency = _fallback_currency(pages)
    selected = {}
    cash_flow_page = None
    previous_context = None
    period_candidates = {}
    found_sections = set()
    for page_no, page in pages:
        section = _statement_section(page, cash_flow_page, page_no)
        continuation = False
        if not section and previous_context and page_no == previous_context[0] + 1:
            first_line = re.sub(r"\s+", "", " ".join(page.splitlines()[:2]))
            if first_line.startswith("과목") and "주석" in first_line:
                section = previous_context[1]
                continuation = True
        if not section:
            continue
        years = previous_context[2] if continuation else _header_years(page)
        unit = previous_context[3] if continuation else _unit_context(page, fallback_currency)
        if not years or not unit:
            continue
        if not continuation:
            for year, ending in _period_ends(page).items():
                if year in years:
                    period_candidates.setdefault(year, set()).add(ending)
        found_sections.add(section)
        previous_context = (page_no, section, years, unit)
        if section == "cash_flow":
            cash_flow_page = page_no
        currency, multiplier = unit
        related_columns = bool(re.search(r"of which:\s*related", " ".join(page.splitlines()[:20]), re.I))
        for raw_line in page.splitlines():
            parsed = _row_values(raw_line, section, related_columns)
            if not parsed:
                continue
            item, label, values, quote = parsed
            for year, value in zip(years, values):
                selected.setdefault((year, item), []).append((value, label, page_no, quote, currency, multiplier))

    facts, warnings = [], []
    ends = {year: next(iter(values)) for year, values in period_candidates.items() if len(values) == 1}
    for year, values in period_candidates.items():
        if len(values) > 1:
            warnings.append(f"FY{year}: 재무제표 간 결산일이 달라 기간을 확정하지 않았습니다.")
    if not selected:
        return [], ["제목·연도 열·통화 단위를 함께 확인할 수 있는 연결 재무제표 표를 찾지 못했습니다."]
    for (year, item), candidates in sorted(selected.items()):
        if len({(row[0], row[4], row[5]) for row in candidates}) != 1:
            warnings.append(f"FY{year} {item}: 정식 표 내 후보값 또는 단위가 달라 자동 선택하지 않았습니다.")
            continue
        value, label, page_no, quote, currency, multiplier = candidates[0]
        ending = ends.get(year, "")
        facts.append(FinancialFact(
            entity_id=entity_id, fiscal_year=year, standard_item=item,
            original_label=label, original_value=value, normalized_value=value * multiplier,
            currency=currency, unit_multiplier=multiplier,
            period_start=_annual_start(ending) if item in FLOW_ITEMS else "",
            period_end=ending, reporting_scope="연결", source_id=source.source_id,
            source_locator=f"PAGE {page_no} | 근거: {quote}",
            extraction_method="정식 연결 재무제표 표 파싱", validation_status="원문 검토 필요",
        ))
    by_key = {(fact.fiscal_year, fact.standard_item): fact for fact in facts}
    for year in sorted({fact.fiscal_year for fact in facts}):
        assets, equity = by_key.get((year, "total_assets")), by_key.get((year, "total_equity"))
        if assets and equity and assets.currency == equity.currency and assets.normalized_value >= equity.normalized_value:
            difference = assets.normalized_value - equity.normalized_value
            facts.append(FinancialFact(
                entity_id=entity_id, fiscal_year=year, standard_item="total_liabilities",
                original_label="부채총계 계산값 (자산총계 - 자본총계)", original_value=difference / assets.unit_multiplier,
                normalized_value=difference, currency=assets.currency, unit_multiplier=assets.unit_multiplier,
                period_end=ends.get(year, ""), reporting_scope="연결", source_id=source.source_id,
                source_locator=f"계산: {assets.source_locator} - {equity.source_locator}",
                extraction_method="공식 연결 자산-자본 계산", validation_status="계산값-원문 검토 필요",
            ))
    if found_sections != {"position", "profit", "cash_flow"}:
        warnings.append("재무상태표·손익계산서·현금흐름표 중 일부만 식별했습니다. 누락 항목은 원문 확인이 필요합니다.")
    return facts, warnings


def sufficient_primary_coverage(facts: list[FinancialFact]) -> bool:
    years = {fact.fiscal_year for fact in facts}
    if len(years) < 2:
        return False
    if any(CORE - {fact.standard_item for fact in facts if fact.fiscal_year == year} for year in years):
        return False
    return all(len({(fact.currency, fact.reporting_scope, fact.period_end) for fact in facts if fact.fiscal_year == year}) == 1
               and all(fact.period_end for fact in facts if fact.fiscal_year == year)
               for year in years)
