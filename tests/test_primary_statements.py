class PrimaryStatementTests(unittest.TestCase):
    def setUp(self):
        self.content = b"%PDF-1.7 example"
        self.source = SourceDocument("report.pdf", "공개 링크", sha256=hashlib.sha256(self.content).hexdigest())

    def test_statement_rows_exclude_related_parties_and_separate_accounts(self):
        facts, warnings = extract_primary_statements(REPORT, "company", self.source)
        self.assertTrue(sufficient_primary_coverage(facts))
        self.assertFalse(warnings)
        by_key = {(f.fiscal_year, f.standard_item): f for f in facts}
        self.assertEqual(by_key[2025, "revenue"].normalized_value, 12_636_199_000)
        self.assertEqual(by_key[2025, "cash"].normalized_value, 2_444_680_000)
        self.assertEqual(by_key[2025, "total_liabilities"].normalized_value, 15_995_889_000)
        self.assertEqual(by_key[2025, "net_income"].original_value, 180_921)
        self.assertEqual(by_key[2025, "investing_cash_flow"].normalized_value, -960_896_000)
        self.assertIn("계산", by_key[2025, "total_liabilities"].source_locator)
        ratios = calculate_ratios(facts)
        margin = next(r for r in ratios if r.fiscal_year == 2025 and r.metric_key == "operating_margin")
        self.assertEqual(margin.status, "계산됨")
        self.assertAlmostEqual(margin.value, 648_760 / 12_636_199)

    def test_unknown_currency_does_not_get_assumed(self):
        facts, warnings = extract_primary_statements(REPORT.split("[PAGE 288]")[0], "company", self.source)
        self.assertEqual(facts, [])
        self.assertTrue(warnings)

    def test_complete_primary_tables_bypass_paid_batch(self):
        class NoCallProvider:
            approved_batch = True
            name = "test"
            model = "test"

            def generate_json(self, *args, **kwargs):
                raise AssertionError("AI must not be called for complete statutory tables")

        text = REPORT + "[PAGE 500]\n" + "Unrelated business text. " * 1200
        facts, _, meta = extract_facts_from_text(text, "company", self.source, NoCallProvider())
        self.assertTrue(sufficient_primary_coverage(facts))
        self.assertEqual(meta["usage"], {})
        self.assertEqual(meta["provider"], "원문 표 파싱")

    def test_repair_preserves_previous_values_and_supersedes_conflicts(self):
        project = AnalysisProject("Webuild", EntityProfile("Webuild", entity_id="company"))
        project.sources.append(self.source)
        project.facts.append(FinancialFact("company", 2025, "cash", "old", 1, 1, "EUR",
                                           source_id=self.source.source_id))
        project.narrative["api_usage"] = [{"source_id": self.source.source_id,
                                            "chunks": 90, "conflicts": [{"item": "cash"}]}]
        with patch("partner_finance.primary_repair.extract_pdf_text", return_value=(REPORT, [])):
            count = repair_source_facts(project, self.source, self.content)
        self.assertGreaterEqual(count, 20)
        self.assertEqual(len(project.narrative["reextraction_history"][0]["facts"]), 1)
        self.assertEqual(project.narrative["api_usage"][0]["superseded_by"], "공식 연결 재무제표 행 재대조")
        self.assertTrue(any(r.status == "계산됨" for r in project.ratios))
        _, evidence = packet_content(project)
        self.assertEqual(json.loads(evidence)["extraction_conflicts"], [])

    def test_repair_rejects_changed_source_without_mutation(self):
        project = AnalysisProject("Webuild", EntityProfile("Webuild"))
        with self.assertRaisesRegex(ValueError, "이전 분석 때와 달라"):
            repair_source_facts(project, self.source, b"changed")
        self.assertEqual(project.facts, [])


