"""Conservative extraction from paired columns in official consolidated statements."""
from __future__ import annotations

import re

from .schema import FinancialFact, SourceDocument


LABELS = {
    "position": {
        "Cash and cash equivalents": "cash",
        "Total current assets": "current_assets",
        "Total assets": "total_assets",
        "Total equity": "total_equity",
        "Total current liabilities": "current_liabilities",
    },
    "profit": {
        "Revenue from contracts with customers": "revenue",
        "Operating profit": "operating_income",
        "Profit for the year": "net_income",
    },
    "cash_flow": {
        "Cash flows generated by operating activities": "operating_cash_flow",
        "Cash flows used in investing activities": "investing_cash_flow",
        "Cash flows generated by (used in) financing activities": "financing_cash_flow",
    },
}
NUMBERS = re.compile(r"\(?-?\d[\d,]*(?:\.\d+)?\)?")
CORE = {"revenue", "operating_income", "net_income", "total_assets", "total_equity",
        "current_assets", "current_liabilities", "operating_cash_flow"}


def _pages(text):
    matches = list(re.finditer(r"\[PAGE (\d+)\]", text))
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        yield int(match[1]), text[match.end():end]


def _column_values(line, label):
    if not line.startswith(label + " "):
        return None
    tail = line[len(label):].strip()
    tokens = NUMBERS.findall(tail)
    # A note reference precedes the two year columns; some tables add two
    # related-party columns, which must never be used as headline values.
    if len(tokens) in (3, 5):
        tokens = tokens[1:]
    if len(tokens) == 4:
        tokens = [tokens[0], tokens[2]]
    if len(tokens) != 2 or NUMBERS.sub("", tail).strip():
        return None
    values = []
    for token in tokens:
        negative = token.startswith("(") and token.endswith(")")
        value = float(token.strip("()").replace(",", ""))
        values.append(-value if negative else value)
    return values


def extract_primary_statements(text: str, entity_id: str, source: SourceDocument,
                               scope: str = "연결") -> tuple[list[FinancialFact], list[str]]:
    """Return facts only when two-year consolidated tables and EUR units are explicit."""
    if scope != "연결":
        return [], ["연결 재무제표 행 파싱은 연결 분석에만 적용합니다."]
    pages = list(_pages(text))
    if not pages:
        return [], ["PDF 페이지 표식을 찾지 못했습니다."]
    selected = {}
    cash_flow_page = None
    for page_no, page in pages:
        header = " ".join(page.splitlines()[:12]).lower()
        if "consolidated statement of financial position" in header:
            section = "position"
        elif "consolidated statement of profit or loss" in header:
            section = "profit"
        elif "consolidated statement of cash flows" in header:
            section = "cash_flow"
        elif cash_flow_page is not None and page_no == cash_flow_page + 1:
            section = "cash_flow" if "investing activities" in header else None
        else:
            continue
        if section is None:
            continue
        years = sorted({int(y) for y in re.findall(r"\b20\d{2}\b", header)})
        if len(years) != 2 or not all(2000 <= y <= 2100 for y in years):
            continue
        # Section headings also occur in contents and notes. Require the
        # actual two-column financial statement table and its unit header.
        if not re.search(r"\([^\n)]*000\)\s+Note", page[:900], re.I):
            continue
        if section == "cash_flow":
            cash_flow_page = page_no
        for line in page.splitlines():
            line = " ".join(line.split())
            for label, item in LABELS[section].items():
                values = _column_values(line, label)
                if values is None:
                    continue
                for year, value in zip(years, values):
                    selected.setdefault((year, item), []).append((value, label, page_no, line))

    # Currency cannot be inferred from an OCR-damaged symbol. Require the
    # accompanying accounting note to identify euro and thousand-unit scale.
    nearby_notes = " ".join(page[:5000] for _, page in pages if
                           "functional and presentation currency" in page.lower())
    if not re.search(r"functional and presentation currency.{0,1200}\bEuro\b", nearby_notes, re.I | re.S) or \
            not re.search(r"rounded to the nearest thousand", nearby_notes, re.I):
        return [], ["통화와 천 단위의 원문 근거를 확인하지 못해 표 행 자동 파싱을 보류했습니다."]

    facts = []
    warnings = []
    for (year, item), candidates in sorted(selected.items()):
        if len({candidate[0] for candidate in candidates}) != 1:
            warnings.append(f"FY{year} {item}: 정식 표 내 후보값이 달라 자동 선택하지 않았습니다.")
            continue
        value, label, page_no, quote = candidates[0]
        facts.append(FinancialFact(
            entity_id=entity_id, fiscal_year=year, standard_item=item,
            original_label=label, original_value=value, normalized_value=value * 1000,
            currency="EUR", unit_multiplier=1000,
            period_start=f"{year}-01-01" if item in {"revenue", "operating_income", "net_income",
                                                       "operating_cash_flow", "investing_cash_flow", "financing_cash_flow"} else "",
            period_end=f"{year}-12-31", reporting_scope="연결", source_id=source.source_id,
            source_locator=f"PAGE {page_no} | 근거: {quote}",
            extraction_method="연결 재무제표 행 파싱", validation_status="원문 검토 필요",
        ))
    by_key = {(f.fiscal_year, f.standard_item): f for f in facts}
    for year in sorted({f.fiscal_year for f in facts}):
        assets, equity = by_key.get((year, "total_assets")), by_key.get((year, "total_equity"))
        if assets and equity and assets.normalized_value >= equity.normalized_value:
            difference = assets.normalized_value - equity.normalized_value
            facts.append(FinancialFact(
                entity_id=entity_id, fiscal_year=year, standard_item="total_liabilities",
                original_label="부채총계 계산값 (자산총계 - 자본총계)", original_value=difference / 1000,
                normalized_value=difference, currency="EUR", unit_multiplier=1000,
                period_end=f"{year}-12-31", reporting_scope="연결", source_id=source.source_id,
                source_locator=f"계산: {assets.source_locator} - {equity.source_locator}",
                extraction_method="공식 연결 자산-자본 계산", validation_status="계산값-원문 검토 필요",
            ))
    return facts, warnings


def sufficient_primary_coverage(facts: list[FinancialFact]) -> bool:
    years = {f.fiscal_year for f in facts}
    return len(years) >= 2 and all(
        CORE <= {f.standard_item for f in facts if f.fiscal_year == year} for year in years
    )
